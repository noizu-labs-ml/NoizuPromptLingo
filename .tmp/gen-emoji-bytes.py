# Filter duplicates by primary name
seen_primary = set()
filtered = []
for names, cp in emojis:
    primary = names.split('|')[0]
    if primary in seen_primary:
        continue
    seen_primary.add(primary)
    filtered.append((names, cp))

# Generate case statement entries
for names, cp in filtered:
    char = chr(cp)
    utf8 = char.encode('utf-8')
    byte_str = ''.join(f'\\x{b:02X}' for b in utf8)
    alias_str = '|'.join(names.split('|'))
    padded = f"{alias_str})".ljust(55)
    print(f"    {padded} printf '{byte_str}' ;;")

print(f"\n# Total: {len(filtered)} emojis")

# Also generate the is_known list
print("\n\n# --- _tabbing_is_known_emoji entries ---")
all_names = []
for names, cp in filtered:
    all_names.extend(names.split('|'))

# Group into lines of reasonable length
line = "    "
lines = []
current = []
for name in all_names:
    current.append(name)
    test = '|'.join(current) + ') return 0 ;;'
    if len(test) > 75:
        # Pop last, emit line
        current.pop()
        lines.append('|'.join(current) + ') return 0 ;;')
        current = [name]
lines.append('|'.join(current) + ') return 0 ;;')

for l in lines:
    print(f"    {l}")
